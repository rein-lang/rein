use std::path::PathBuf;
use std::process::ExitCode;

use clap::{Parser, Subcommand, ValueEnum};

// A link reference definition, not an HTML comment: VitePress runs with `markdown.html` off, so `<!-- -->` would show as text.
const GENERATED_NOTICE: &str = "[//]: # \"Generated by `rein docs-cli` from the clap definitions in crates/rein. Do not edit by hand; run website/docs/scripts/generate-cli.sh.\"\n\n";

#[derive(Clone, Copy, ValueEnum)]
enum Format {
    Text,
    Json,
}

#[derive(Parser)]
#[command(name = "rein", version, about = "A small language for agent decision flows")]
struct Cli {
    #[command(subcommand)]
    command: Command,
}

#[derive(Subcommand)]
enum Command {
    /// Check a project directory, or one .rein file, and print diagnostics.
    Check {
        /// Project directory or .rein file.
        #[arg(default_value = ".")]
        path: PathBuf,
    },
    /// Run a flow as a live process. Writes one step per line, reads one answer per line on stdin.
    Run {
        /// Program to run: a `.rein` file, or a name (see `rein list`).
        #[arg(conflicts_with = "root")]
        flow: Option<String>,
        /// Project root. Default: the nearest directory with main.rein.
        #[arg(long)]
        root: Option<PathBuf>,
        /// Function to start from, as its path under the root without `.rein`. Default: `main`.
        #[arg(long)]
        entry: Option<String>,
        /// Speak JSON Lines: one step object out, one `{"key","value"}` answer in, per line.
        #[arg(long)]
        json: bool,
    },
    /// Evaluate one function, for debugging. Agents use `rein run` or `rein step`.
    Eval {
        /// Function name, as its path under the root without `.rein`. Default: `main`.
        #[arg(default_value = "main")]
        function: String,
        /// Project root. Default: the nearest directory with main.rein.
        #[arg(long)]
        root: Option<PathBuf>,
        /// Input value as name=value. Repeat for each input.
        #[arg(long = "set", value_name = "NAME=VALUE")]
        set: Vec<String>,
        /// Print the result as JSON.
        #[arg(long)]
        json: bool,
    },
    /// Step the whole flow from `main`. This is the agent-facing interface: answer one key per call.
    Step {
        /// Program to step: a `.rein` file (its folder is the project root), or a name (see `rein list`).
        #[arg(conflicts_with_all = ["flow", "root", "entry"])]
        program: Option<String>,
        /// Function to start from, as its path under the root without `.rein`. Default: `main`.
        #[arg(long)]
        entry: Option<String>,
        /// Project root. Default: the nearest directory with main.rein.
        #[arg(long, conflicts_with = "flow")]
        root: Option<PathBuf>,
        /// Program to step, by name (see `rein list`). Same as the positional program.
        #[arg(long, conflicts_with = "root")]
        flow: Option<String>,
        /// Answer as key=value, such as `merge_pr.ci=green`. Repeat for each answer.
        #[arg(long = "answer", value_name = "KEY=VALUE")]
        answer: Vec<String>,
        /// Value of a `string` parameter of the entry function, as name=value. Repeat for each input.
        #[arg(long = "input", value_name = "NAME=VALUE")]
        input: Vec<String>,
        /// Read the whole request as JSON from stdin. Output is always JSON.
        #[arg(long)]
        stdin: bool,
        /// Print the response as JSON.
        #[arg(long)]
        json: bool,
    },
    /// Print a function's schema as JSON.
    Describe {
        /// Function name. Default: `main`.
        #[arg(default_value = "main")]
        function: String,
        /// Project root. Default: the nearest directory with main.rein.
        #[arg(long)]
        root: Option<PathBuf>,
    },
    /// Print the program graph: functions, questions, branches, outcomes, and hand-offs. With answers, mark the
    /// path the flow takes.
    Graph {
        #[command(flatten)]
        args: graph::GraphArgs,
    },
    /// Debug a program in the browser: set inputs and answers, step through, and watch the path the flow takes.
    Debug {
        #[command(flatten)]
        args: debug::DebugArgs,
    },
    /// Show the agents that use rein now: their programs, answers and the step each run waits on, in a browser page.
    Watch {
        #[command(flatten)]
        args: watch::WatchArgs,
    },
    /// List the programs visible from here, as `ls` lists files: names, or `-l` for details. Operands are name globs.
    #[command(alias = "flows")]
    List {
        #[command(flatten)]
        args: list::ListArgs,
    },
    /// Print a program's source: its manifest and every .rein file.
    Show {
        /// Program name (see `rein list`).
        name: String,
    },
    /// Serve the agent interface. Holds live runs in memory.
    Serve {
        /// Speak MCP on stdio. The only transport today.
        #[arg(long)]
        mcp: bool,
    },
    /// Print the block an agent needs to use the visible flows.
    AgentContext {
        /// Output format.
        #[arg(long, value_enum, default_value = "text")]
        format: Format,
    },
    /// The agent hook entry point. Reads one event on stdin. Run by the agent, not by hand.
    Hook {
        /// The agent that sends the event, such as `claude-code`. Sets polyhook's caller.
        #[arg(long)]
        caller: Option<String>,
    },
    /// Install a program package: runs `pnpm add` with these arguments.
    ///
    /// The arguments go to pnpm unchanged, so any pnpm flag works. `-g` or `--global` installs for the user: it runs
    /// in `<user programs folder>/npm/`, and rein does not pass it on. Without `-g`, it runs in the repo's
    /// `rein/npm/`. Outside a repository, use `-g`. `--ignore-scripts` is added first, unless the arguments set it.
    Install {
        /// Arguments for `pnpm add`, such as `pr-handling@^1`, `file:../pr-handling` or `--save-exact`.
        #[arg(required = true, trailing_var_arg = true, allow_hyphen_values = true, value_name = "ARGS")]
        args: Vec<String>,
    },
    /// Remove an installed program package: runs `pnpm remove` with these arguments. `-g` picks the user folder.
    Uninstall {
        /// Arguments for `pnpm remove`, such as a package name. `-g` picks the user folder.
        #[arg(required = true, trailing_var_arg = true, allow_hyphen_values = true, value_name = "ARGS")]
        args: Vec<String>,
    },
    /// Update installed program packages: runs `pnpm update --ignore-scripts` with these arguments. `-g` picks the
    /// user folder.
    Update {
        /// Arguments for `pnpm update`, such as a package name or `--latest`. `-g` picks the user folder.
        #[arg(trailing_var_arg = true, allow_hyphen_values = true, value_name = "ARGS")]
        args: Vec<String>,
    },
    /// Run the language server on stdio.
    Lsp,
    /// Run the debug adapter on stdio (Debug Adapter Protocol). The VS Code extension starts it.
    Dap,
    /// Print the command reference as Markdown.
    #[command(hide = true)]
    DocsCli,
}

fn main() -> ExitCode {
    let code = match Cli::parse().command {
        Command::Check { path } => cli::check(&path),
        Command::Run { flow, root, entry, json } => live_run::run(flow, root, entry, json),
        Command::Eval { function, root, set, json } => cli::eval(&function, root, &set, json),
        Command::Step { program, entry, root, flow, answer, input, stdin, json } => {
            cli::step(entry, root, flow.or(program), &answer, &input, stdin, json)
        }
        Command::Describe { function, root } => cli::describe(&function, root),
        Command::Graph { args } => graph::run(&args),
        Command::Debug { args } => debug::run(&args),
        Command::Watch { args } => watch::run(&args),
        Command::List { args } => list::run(&args),
        Command::Show { name } => programs::show(&name),
        Command::Serve { mcp: true } => mcp::serve(),
        Command::Serve { mcp: false } => {
            eprintln!("error: only `rein serve --mcp` is supported");
            1
        }
        Command::AgentContext { format } => cli::agent_context(matches!(format, Format::Json)),
        Command::Hook { caller } => hook::run(caller.as_deref()),
        Command::Install { args } => packages::run("add", &args),
        Command::Uninstall { args } => packages::run("remove", &args),
        Command::Update { args } => packages::run("update", &args),
        Command::Lsp => lsp::serve(),
        Command::Dap => dap::serve(),
        Command::DocsCli => {
            print!("{}", cli_reference());
            0
        }
    };
    ExitCode::from(code)
}

/// The command reference, as Markdown, for `website/docs/reference/cli.md`.
fn cli_reference() -> String {
    let options = clap_markdown::MarkdownOptions::new().show_footer(false);
    format!(
        "{GENERATED_NOTICE}{}",
        clap_markdown::help_markdown_custom::<Cli>(&options)
    )
}

